// Re-bundles the parts of Google's @material/material-color-utilities that the
// theme uses into one ESM file under src/vendor.
//
// Why: the published 0.4.0 package contains extensionless relative imports
// (e.g. `from './dynamic_color'`), which Node's ESM loader rejects. Astro's SSR
// loads dependencies through Node, so importing the package directly fails at
// build time, and a theme cannot change the host site's Vite config. The
// algorithm is unchanged; only module resolution is done ahead of time.
//
// Usage: node tools/bundle-color-utilities.mjs
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
// The package's "exports" map hides package.json, so read it from node_modules directly.
const pkgDir = path.join(root, 'node_modules/@material/material-color-utilities');
const { version } = JSON.parse(await readFile(path.join(pkgDir, 'package.json'), 'utf8'));
const outfile = path.join(root, 'src/vendor/material-color-utilities.js');

const exportsList = [
  'Hct', 'MaterialDynamicColors', 'argbFromHex', 'hexFromArgb',
  'SchemeTonalSpot', 'SchemeNeutral', 'SchemeVibrant', 'SchemeExpressive',
  'SchemeFidelity', 'SchemeContent', 'SchemeMonochrome',
];

const result = await build({
  stdin: {
    contents: `export { ${exportsList.join(', ')} } from '@material/material-color-utilities';`,
    resolveDir: root,
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: true,
  legalComments: 'inline',
  write: false,
  // Extensionless specifiers are resolved here, at bundle time.
  resolveExtensions: ['.js'],
});

const banner = `/**
 * Generated by tools/bundle-color-utilities.mjs from
 * @material/material-color-utilities@${version} (Copyright Google LLC, Apache-2.0).
 * Do not edit; re-run the tool after updating the devDependency.
 */
`;
await writeFile(outfile, banner + result.outputFiles[0].text);
console.log(`Wrote ${path.relative(root, outfile)} from v${version}`);
